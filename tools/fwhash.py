"""
Pin a firmware image: emit a C header with its size and SHA-256.

The bootloader in firmware/09-securebootloader compiles this header in, then
refuses to start whatever sits in QSPI unless it hashes to the same value.
Any change to the application therefore needs the bootloader rebuilt and
reflashed, which is the point.

    ./fwhash.py 09-securebootloader-app.bin > app_hash.h
"""

import hashlib
import os
import sys


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: fwhash.py IMAGE.bin > header.h")

    path = sys.argv[1]
    with open(path, "rb") as f:
        data = f.read()
    if not data:
        sys.exit(f"{path} is empty")

    digest = hashlib.sha256(data).digest()
    rows = [", ".join(f"0x{b:02x}" for b in digest[i:i + 8])
            for i in range(0, len(digest), 8)]

    print(f"/* Generated by tools/fwhash.py from {os.path.basename(path)}, do not edit */")
    print(f"/* sha256 {digest.hex()} */")
    print()
    print(f"#define APP_IMAGE_SIZE  {len(data)}UL")
    print()
    print("static const uint8_t app_image_sha256[32] = {")
    for row in rows:
        print(f"    {row},")
    print("};")


if __name__ == "__main__":
    main()
