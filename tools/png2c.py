"""
Convert a PNG into a C header for the LTDC.

The output is an 8-bit indexed bitmap plus a 256-entry RGB565 palette,
which costs one byte per pixel instead of two. On a part with 64 KB of
flash that difference decides whether the image fits at all.

Index 0 is reserved for transparency, so the logo can be drawn over
anything without a matte. The remaining 255 entries hold the quantised
colours.

    ./png2c.py logo.png --size 160 --out logo.h

Needs Pillow:  pip install pillow
"""

import argparse
import os
import sys

try:
    from PIL import Image
except ImportError:
    sys.exit("Pillow is missing — pip install pillow")


def rgb565(r, g, b):
    """Pack 8-8-8 into 5-6-5. Green keeps the extra bit: the eye is more
    sensitive to it than to red or blue."""
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def convert(path, target, alpha_cutoff):
    img = Image.open(path).convert("RGBA")

    # Scale so the longest side matches, keeping the aspect ratio
    w, h = img.size
    scale = target / max(w, h)
    new_size = (max(1, round(w * scale)), max(1, round(h * scale)))
    img = img.resize(new_size, Image.LANCZOS)
    w, h = img.size

    alpha = img.getchannel("A")

    # Quantise to 255 colours, leaving index 0 free for transparency.
    # Compositing on white first stops the quantiser wasting entries on
    # the fringe pixels around transparent edges.
    flat = Image.new("RGB", img.size, (255, 255, 255))
    flat.paste(img, mask=alpha)
    quant = flat.quantize(colors=255, method=Image.MEDIANCUT)

    palette = quant.getpalette()[: 255 * 3]
    indices = list(quant.getdata())
    alpha_data = list(alpha.getdata())

    # Shift every index up by one and mark the see-through pixels as 0
    out = bytearray(w * h)
    used = set()
    for i, (idx, a) in enumerate(zip(indices, alpha_data)):
        if a < alpha_cutoff:
            out[i] = 0
        else:
            out[i] = idx + 1
            used.add(idx + 1)

    return w, h, palette, out, len(used)


def emit(name, w, h, palette, data, out_file):
    lines = []
    a = lines.append

    a("// SPDX-License-Identifier: MIT")
    a("/*!")
    a("****************************")
    a(f"\\file       {os.path.basename(out_file) if out_file != '-' else name + '.h'}")
    a("\\brief      Generated by png2c.py, do not edit.")
    a("")
    a("\\details")
    a(f"  {w} x {h}, 8-bit indexed, {w * h} bytes of pixels plus a 256-entry")
    a("  RGB565 palette. Index 0 is transparent.")
    a("****************************")
    a("*/")
    a("")
    a("#ifndef LOGO_H")
    a("#define LOGO_H")
    a("")
    a("#include <stdint.h>")
    a("")
    a(f"#define {name.upper()}_WIDTH  {w}U")
    a(f"#define {name.upper()}_HEIGHT {h}U")
    a("")

    # Palette: entry 0 is never drawn, so its value does not matter
    a(f"static const uint16_t {name}_palette[256] = {{")
    entries = ["0x0000"]
    for i in range(255):
        r, g, b = palette[i * 3 : i * 3 + 3]
        entries.append(f"0x{rgb565(r, g, b):04X}")
    for i in range(0, 256, 8):
        a("    " + ", ".join(entries[i : i + 8]) + ",")
    a("};")
    a("")

    a(f"static const uint8_t {name}_data[{w * h}] = {{")
    for i in range(0, len(data), 16):
        chunk = ", ".join(f"0x{b:02X}" for b in data[i : i + 16])
        a("    " + chunk + ",")
    a("};")
    a("")
    a("#endif /* LOGO_H */")

    text = "\n".join(lines) + "\n"
    if out_file == "-":
        sys.stdout.write(text)
    else:
        with open(out_file, "w") as f:
            f.write(text)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("png")
    p.add_argument("--size", type=int, default=160,
                   help="longest side in pixels (default 160)")
    p.add_argument("--name", default="logo",
                   help="C identifier prefix (default logo)")
    p.add_argument("--alpha", type=int, default=128,
                   help="alpha below this becomes transparent (default 128)")
    p.add_argument("--out", default="logo.h",
                   help="output file, or - for stdout")
    args = p.parse_args()

    w, h, palette, data, used = convert(args.png, args.size, args.alpha)
    emit(args.name, w, h, palette, data, args.out)

    total = w * h + 512
    transparent = sum(1 for b in data if b == 0)

    print(f"{args.png} -> {args.out}", file=sys.stderr)
    print(f"  {w} x {h}, {used} colours used", file=sys.stderr)
    print(f"  {w * h} bytes of pixels + 512 of palette = {total} bytes",
          file=sys.stderr)
    print(f"  {transparent * 100 // (w * h)} % transparent", file=sys.stderr)

    if total > 40000:
        print("  warning: that is a large slice of 64 KB of flash",
              file=sys.stderr)


if __name__ == "__main__":
    main()
